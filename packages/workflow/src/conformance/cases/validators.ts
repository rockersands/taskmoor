import type { CompareOp, ValidatorDef } from '../../model';
import type { ConformanceCase } from '../case';
import { actor, item, reviewed, section, validated } from './fixtures';

const c = section('WF-004', 'validators', '01a 3.3, WF-004');

function startCase(
  slug: string,
  title: string,
  validators: ValidatorDef[],
  layout: string[],
  itemState: ReturnType<typeof item>,
  who: ReturnType<typeof actor>,
  entered: Record<string, unknown> | undefined,
  pass: boolean,
  blockedBy?: string,
  message?: string,
  verify?: string,
): ConformanceCase {
  return c(slug, {
    kind: 'transition',
    title,
    workflow: validated(validators, layout),
    item: itemState,
    actor: who,
    request: { transition: 'start', ...(entered ? { fields: entered } : {}) },
    expect: pass
      ? { outcome: 'ok', status: 'in-progress' }
      : {
          outcome: 'blocked',
          by: 'validator',
          name: blockedBy ?? validators[0]?.type ?? 'validator',
          ...(message ? { message } : {}),
        },
    ...(verify ? { verify } : {}),
  });
}

const OPS: CompareOp[] = ['=', '!=', '>', '>=', '<', '<='];
const holds = (op: CompareOp, l: number, r: number) =>
  op === '='
    ? l === r
    : op === '!='
      ? l !== r
      : op === '>'
        ? l > r
        : op === '>='
          ? l >= r
          : op === '<'
            ? l < r
            : l <= r;
const opSlug = (op: CompareOp) =>
  op === '='
    ? 'eq'
    : op === '!='
      ? 'ne'
      : op === '>'
        ? 'gt'
        : op === '>='
          ? 'ge'
          : op === '<'
            ? 'lt'
            : 'le';

/** Date compare, every operator, with the due date before, on and after the start date. */
const dateCompareCases: ConformanceCase[] = OPS.flatMap((op) =>
  [
    ['before', '2026-10-11'],
    ['same', '2026-10-12'],
    ['after', '2026-10-13'],
  ].map(([rel, due]) =>
    startCase(
      `date-compare-${opSlug(op)}-${rel}`,
      `Date compare: due ${op} start with due ${rel} start`,
      [{ type: 'date-compare', field: 'due', op, other: 'start' }],
      [],
      item({ fields: { start: '2026-10-12', due } }),
      actor('alice'),
      undefined,
      holds(op, Date.parse(due as string), Date.parse('2026-10-12')),
      'date-compare',
    ),
  ),
);

