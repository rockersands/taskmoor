/**
 * The load-test report (M1-104): the results of each tier against the targets of spec 05b
 * section 3 and NFR-003, and a sizing table computed from them, so nobody edits it by hand.
 *
 * Sizing: each tier's CPU seconds per request (server and Postgres apart) times the request
 * rate a tier of that many people makes, at 60% utilisation, gives the cores each needs; memory
 * is the server's peak resident size with headroom, and Postgres's from the dataset size rule
 * of deploy/README.md. Numbers come from this machine; on other hardware they scale roughly
 * with single-core speed.
 */
export interface TierResult {
  users: number;
  seconds: number;
  k6Exit: number;
  requests: number;
  requestsPerSecond: number;
  errorRate: number;
  p95: Record<string, number>;
  p50: Record<string, number>;
  serverCpuSeconds: number;
  postgresCpuSeconds: number;
  serverPeakRssMb: number;
}

export interface LoadData {
  label: string;
  at: string;
  items: number;
  hold: string;
  ramp: string;
  machine: { cpus: number; cpuModel: string; memoryGb: number; platform: string };
  tiers: TierResult[];
}

/** p95 targets in milliseconds: spec 05b section 3, and NFR-003's 500 ms for the rest. */
export const TARGETS: Record<string, { ms: number; source: string }> = {
  open_ticket: { ms: 300, source: 'Open a ticket, cold: 300 ms' },
  search: { ms: 300, source: 'Query by track, status, ordering: 300 ms' },
  board: { ms: 1000, source: 'Board to interactive: 1 s' },
  history: { ms: 100, source: 'Simple API read: 100 ms' },
  edit: { ms: 500, source: 'Interactive request (NFR-003): 500 ms' },
  comment: { ms: 500, source: 'Interactive request (NFR-003): 500 ms' },
  create: { ms: 200, source: 'Create ticket round trip: 200 ms' },
};

const NAMES: Record<string, string> = {
  open_ticket: 'Open a ticket',
  search: 'Search (track, status, order)',
  board: 'Board data',
  history: 'Ticket history',
  edit: 'Edit a summary',
  comment: 'Comment',
  create: 'Create a ticket',
};

/** Cores needed for `rps` requests a second at `cpuPerRequest` seconds each, 60% busy. */
export function coresFor(rps: number, cpuPerRequest: number): number {
  return Math.max(1, Math.ceil((rps * cpuPerRequest) / 0.6));
}

/** The request rate of `users` people, from what a measured tier of people sent. */
export function rateFor(users: number, measured: TierResult): number {
  return (measured.requestsPerSecond / measured.users) * users;
}

const fmt = (n: number) => n.toLocaleString('en');

export function renderReport(data: LoadData): string {
  const lines: string[] = [];
  lines.push('# Load tests and sizing');
  lines.push('');
  lines.push(
    `Generated by \`pnpm load\` (M1-104, ADR-082) on ${data.at.slice(0, 10)} from \`docs/ops/data/load-${data.label}.json\`; do not edit by hand.`,
  );
  lines.push('');
  lines.push(
    `Dataset: ${fmt(data.items)} tickets. Each tier ramps up over ${data.ramp} and holds for ${data.hold}. Machine: ${data.machine.cpuModel}, ${data.machine.cpus} cores, ${data.machine.memoryGb} GB (${data.machine.platform}), server and PostgreSQL 16 on the same machine as k6. Every person rests 5 to 15 seconds between steps; a quarter of requests write.`,
  );
  lines.push('');
  lines.push('## Results');
  lines.push('');
  const tierHead = data.tiers.map((t) => `${fmt(t.users)} people`).join(' | ');
  lines.push(`| p95 (ms) | Target | ${tierHead} |`);
  lines.push(`|---|---|${data.tiers.map(() => '---|').join('')}`);
  for (const action of Object.keys(NAMES)) {
    const target = TARGETS[action] as { ms: number };
    const cells = data.tiers.map((t) => {
      const v = t.p95[action] ?? 0;
      return v <= target.ms ? `${fmt(v)}` : `**${fmt(v)}** (over)`;
    });
    lines.push(`| ${NAMES[action]} | ${fmt(target.ms)} | ${cells.join(' | ')} |`);
  }
  lines.push(
    `| Requests a second | | ${data.tiers.map((t) => fmt(t.requestsPerSecond)).join(' | ')} |`,
  );
  lines.push(
    `| Failed requests | | ${data.tiers.map((t) => `${(t.errorRate * 100).toFixed(2)}%`).join(' | ')} |`,
  );
  lines.push(
    `| Server CPU (s) / Postgres CPU (s) | | ${data.tiers.map((t) => `${fmt(t.serverCpuSeconds)} / ${fmt(t.postgresCpuSeconds)}`).join(' | ')} |`,
  );
  lines.push(
    `| Server peak memory (MB) | | ${data.tiers.map((t) => fmt(t.serverPeakRssMb)).join(' | ')} |`,
  );
  lines.push('');
  const missed = data.tiers.flatMap((t) =>
    Object.entries(t.p95)
      .filter(([a, v]) => v > (TARGETS[a]?.ms ?? Number.POSITIVE_INFINITY))
      .map(([a]) => `${NAMES[a]} at ${fmt(t.users)} people`),
  );
  lines.push(
    missed.length === 0
      ? 'Every p95 target was met at every tier.'
      : `Over target: ${missed.join('; ')}. Targets are for the reference hardware with the server and database on separate machines; see the sizing below.`,
  );
  // The busiest tier that still met every target: what one API process served.
  const within = data.tiers
    .filter((t) =>
      Object.entries(t.p95).every(([a, v]) => v <= (TARGETS[a]?.ms ?? Number.POSITIVE_INFINITY)),
    )
    .sort((a, b) => b.users - a.users)[0];
  if (within && missed.length > 0) {
    lines.push('');
    lines.push(
      `One API process met every target up to ${fmt(within.users)} people (${fmt(within.requestsPerSecond)} requests a second); past that, add API processes as the sizing says.`,
    );
  }
  lines.push('');
  // The busiest tier gives the most reliable cost per request.
  const busiest = [...data.tiers].sort((a, b) => b.requests - a.requests)[0];
  lines.push('## Sizing');
  lines.push('');
  if (!busiest || busiest.requests === 0) {
    lines.push('No requests were measured.');
    return `${lines.join('\n')}\n`;
  }
  const serverPerRequest = busiest.serverCpuSeconds / busiest.requests;
  const pgPerRequest = busiest.postgresCpuSeconds / busiest.requests;
  lines.push(
    `From the ${fmt(busiest.users)}-people tier: ${(serverPerRequest * 1000).toFixed(1)} ms of server CPU and ${(pgPerRequest * 1000).toFixed(1)} ms of PostgreSQL CPU per request, ${(busiest.requestsPerSecond / busiest.users).toFixed(3)} requests a second per active person. Cores are sized for 60% use; add one API process per extra core.`,
  );
  lines.push('');
  lines.push('| Active people | Requests a second | Taskmoor (API and worker) | PostgreSQL |');
  lines.push('|---|---|---|---|');
  const peakRss = Math.max(...data.tiers.map((t) => t.serverPeakRssMb));
  for (const users of [50, 500, 2000, 5000]) {
    const rps = rateFor(users, busiest);
    const appCores = coresFor(rps, serverPerRequest);
    const pgCores = coresFor(rps, pgPerRequest);
    const appMemory = Math.max(1, Math.ceil(((peakRss / 1024) * 1.5 + 0.5) * appCores));
    const pgMemory = Math.max(4, Math.ceil(data.items / 250_000) * 2 + Math.ceil(users / 500) * 2);
    lines.push(
      `| ${fmt(users)} | ${rps.toFixed(1)} | ${appCores} cores, ${appMemory} GB | ${pgCores} cores, ${pgMemory} GB |`,
    );
  }
  lines.push('');
  lines.push(
    'PostgreSQL memory follows the dataset: shared buffers of a quarter of memory, enough to hold the hot tickets and indexes. For 10M tickets plan 32 GB or more (deploy/README.md). Rerun `pnpm load` on the target hardware before committing to a size.',
  );
  return `${lines.join('\n')}\n`;
}
